const clamp = (v, lo, hi) => Math.max(lo, Math.min(hi, v))
const clamp01 = (v) => clamp(v, 0, 1)
const r1 = (v) => Math.round(v * 10) / 10
const r2 = (v) => Math.round(v * 100) / 100
/** 数值项：非正数、非有限、空串一律当"没量"，不兜底不编造 */
function meas(val) {
  const n = Number(val)
  return Number.isFinite(n) && n > 0 ? n : 0
}

